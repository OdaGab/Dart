void main() {
  // Exemplo de variáveis String, int e double

  // String: para armazenar texto
  String nome = "Dart";
  print("Olá, $nome!");

  // int: para armazenar números inteiros
  int ano = 2024;
  print("Estamos no ano de $ano.");

  // double: para armazenar números de ponto flutuante
  double versao = 3.3;
  print("A versão atual do Dart é $versao.");
}
